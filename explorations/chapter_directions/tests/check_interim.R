source("explorations/chapter_directions/interim_helpers.R")
out<-id_output_dir();cd_verify(file.path(CD,"earnings_amendment.sha256"));cd_verify(file.path(CD,"interim_amendment.sha256"))
checks<-list();check<-function(name,ok) {
  stopifnot(isTRUE(ok));checks[[length(checks)+1]]<<-tibble(check=name,status="passed")
}
fails<-function(expr)inherits(tryCatch(force(expr),error=function(e)e),"error")
target<-tibble(year=c(2025L,2026L),qtr=c(4L,1L))
toy<-tibble(county_fips="01001",year=c(2024L,2025L,2025L,2026L),qtr=c(4L,1L,4L,1L),emp=10,disclosed=TRUE,avg_wkly_wage=c(100,100,110,121))
check("two_quarter_mean_uses_both_year_pairs",abs(interim_window(toy,target)$change-mean(log(c(1.1,1.21))))<1e-12)
check("missing_declared_quarter_stops",fails(interim_window(toy[-4,],target)))
toy$disclosed[4]<-FALSE;check("suppressed_quarter_excludes_county",nrow(interim_window(toy,target))==0)
toy$disclosed[4]<-TRUE;toy$emp[4]<-9;check("employment_threshold_applies_to_each_quarter",nrow(interim_window(toy,target))==0)
q<-read_parquet(file.path(out,"earnings_interim.parquet"));cd_keys(q,c("industry_code","county_fips","year","qtr"))
check("unique_string_county_keys",is.character(q$county_fips)&&all(grepl("^[0-9]{5}$",q$county_fips)))
check("suppression_propagates",all(is.na(q$avg_wkly_wage[!q$disclosed])))
lead_target<-tibble(year=c(2024L,2025L,2025L),qtr=c(4L,1L,2L));crop<-filter(q,industry_code=="111")
check("full_prior_lead_matches_frozen_helper",isTRUE(all.equal(arrange(interim_window(crop,lead_target),county_fips),arrange(cd_window(crop,2025L),county_fips),tolerance=1e-12)))
r<-read_csv(file.path(out,"earnings_interim_estimates.csv"),show_col_types=FALSE)
cd_keys(r,c("window","tau","specification","weights","term"))
check("complete_declared_specification_grid",nrow(r) %in% c(46L,51L))
expo<-read_csv("explorations/episode_2025/domestic_wage_exposure_frozen.csv",col_types=cols(county_fips="c",state_fips="c",cz_id="c",.default=col_guess()))
d<-interim_window(crop,target) %>% inner_join(expo,by="county_fips") %>% group_by(state_fips) %>% filter(n()>=2) %>% ungroup() %>% mutate(D=S_winsorized*cut_us)
independent<-coef(lm(change ~ D + S_winsorized + factor(state_fips),data=d))[["D"]]
primary<-filter(r,specification=="crop_primary",window=="interim_2025Q4_2026Q1")
check("independent_base_R_primary_reproduction",abs(independent-primary$estimate)<1e-10)
common<-filter(r,specification=="crop_primary",grepl("_common_sample$",window))
check("common_quarter_samples_and_mean_coefficient",all(common$n==primary$n)&&abs(mean(common$estimate)-primary$estimate)<1e-10)
check("intervals_and_unavailable_fits_retained",all(r$low[r$status=="estimated"]<=r$high[r$status=="estimated"])&&all(is.na(r$low[r$status!="estimated"])))
check("original_pre_policy_results_preserved",file.exists(file.path(out,"earnings_pre_estimates.csv"))&&!file.exists(file.path(out,"earnings_post_completed.json")))
cd_write(bind_rows(checks),out,"interim_validation.csv")
cat("Interim checks passed:",length(checks),"\n")
